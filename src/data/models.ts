/** Gallery images per model family: client work first, then the Boldux catalogue (generated by scripts/prepare-assets.py). */
export function modelGallery(slug: ModelSlug): string[] {
  const list = [...(CLIENT_FIRST[slug] ?? []), ...(galleries[slug] ?? [])];
  return list.filter((src, i) => list.indexOf(src) === i);
}

